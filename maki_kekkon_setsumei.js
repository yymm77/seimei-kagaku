  /* "S2-1" → { code, na, yoyaku, honbun, tsuyosa } */
  function makiSetsumei(code, men) {
    var m = String(code).toUpperCase().match(/^([SK][1-5])-?([1-3])?$/);
    if (!m) return null;
    var tbl = (men === 'taijin') ? TAIJIN : NAIMEN;
    var d = tbl[m[1]];
    if (!d) return null;
    return { code: m[1], na: d.na, yoyaku: d.yoyaku, honbun: d.honbun,
             tsuyosa: m[2] ? Number(m[2]) : null,
             men: (men === 'taijin') ? '対人性格' : '内面性格' };
  }

  /* タイプの並びをまとめて説明にする */
  function makiSetsumeiList(codes, men) {
    return (codes || []).map(function (c) { return makiSetsumei(c, men); })
                        .filter(function (x) { return x; });
  }

