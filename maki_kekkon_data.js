  /* 基礎数値を出す（原典42〜43頁）
   *   seiKaku : 姓の各字の画数の配列（例 吉田 → [6, 5]）
   *   meiKaku : 名の各字の画数の配列（例 桂子 → [10, 3]）
   * 戻り値 { A, B, C, seiJisu, meiJisu }
   */
  function makiKekkonPoints(seiKaku, meiKaku) {
    var sum = function (a) {
      return a.reduce(function (x, y) { return x + y; }, 0);
    };
    return {
      A: sum(seiKaku) + sum(meiKaku),
      B: sum(meiKaku),
      C: meiKaku[0],
      seiJisu: seiKaku.length,
      meiJisu: meiKaku.length
    };
  }

  /* 結婚好適期を引く
   *   seiJisu : 姓の字数（1・2・3）
   *   A       : 基礎数値〔A〕
   * 戻り値 { seiJisu, A, hyou, koteki:[{ order, age, from, to, star }×7] }
   *         表に無いときは null
   */
  function makiKekkonKoteki(seiJisu, A) {
    var t = TABLES[seiJisu];
    if (!t) return null;
    var row = t[A];
    if (!row) return null;

    return {
      seiJisu: seiJisu,
      A: A,
      hyou: ['数表④', '数表⑤', '数表⑥'][seiJisu - 1],
      koteki: row.map(function (s, i) {
        var star = s.charAt(0) === '*';
        var age = star ? s.slice(1) : s;
        var p = age.split('-');
        // 数字ひとつ＝その誕生日から1年間。数字ふたつ＝6か月ずれた1年間。
        var start = parseInt(p[0], 10) + (p.length > 1 ? 0.5 : 0);
        return {
          order: i + 1,
          age: age,            // 原典の表記（"19" / "19-20"）
          start: start,        // 山の始まり（歳・小数）
          end: start + 1,      // 山の終わり（どれも1年間）
          center: start + 0.5, // 山の中心
          star: star           // 特別に盛りあがりの大きい山
        };
      })
    };
  }

  /* 収録範囲（画面に「表の範囲外です」と出すときの案内用） */
